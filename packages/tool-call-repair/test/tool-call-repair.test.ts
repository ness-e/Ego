import { describe, it, expect } from "vitest";
import {
  ToolCallRepairEngine,
  extractAndRepairJson,
  normalizeToolArguments,
  coerceBoolean,
  coerceNumber,
  coerceArray,
} from "../src/index.js";

describe("Tool Call Repair Suite (OCLW-03 & OCLW-04)", () => {
  describe("Extracción y Reparación de JSON Truncado", () => {
    it("debe extraer y reparar un JSON truncado sin comillas ni llaves de cierre", () => {
      const truncated = '{"path": "src/index.ts", "count": 42, "status": "pend';
      const fragment = extractAndRepairJson(truncated);
      expect(fragment).not.toBeNull();
      expect(fragment!.repaired).toBe(true);

      const parsed = JSON.parse(fragment!.json);
      expect(parsed.path).toBe("src/index.ts");
      expect(parsed.count).toBe(42);
      expect(parsed.status).toBe("pend");
    });

    it("debe reparar arrays truncados con objetos anidados", () => {
      const truncated = '{"items": [{"id": 1, "name": "alfa"}, {"id": 2';
      const fragment = extractAndRepairJson(truncated);
      expect(fragment).not.toBeNull();
      const parsed = JSON.parse(fragment!.json);
      expect(parsed.items).toBeInstanceOf(Array);
      expect(parsed.items[0].name).toBe("alfa");
    });

    it("retorna null si el texto no contiene ningún fragmento JSON reconocible", () => {
      const fragment = extractAndRepairJson("Esto es simplemente texto plano sin JSON");
      expect(fragment).toBeNull();
    });
  });

  describe("Extracción Gramatical Multi-Sintaxis", () => {
    it("debe extraer tool call en formato XML-ish <function=...>", () => {
      const text =
        'Voy a leer el archivo:\n<function=read_file><parameter=path>docs/README.md</parameter></function>\nListo.';
      const calls = ToolCallRepairEngine.extractFromText(text);
      expect(calls).toHaveLength(1);
      expect(calls[0].name).toBe("read_file");
      expect(calls[0].arguments.path).toBe("docs/README.md");

      const cleaned = ToolCallRepairEngine.stripToolCalls(text);
      expect(cleaned).toBe("Voy a leer el archivo:\n\nListo.");
    });

    it("debe extraer tool call en formato bracket [tool: write_file {...}]", () => {
      const text =
        'Aplicando cambio:\n[tool: write_file {"path": "test.txt", "content": "hola mundo"}]';
      const calls = ToolCallRepairEngine.extractFromText(text);
      expect(calls).toHaveLength(1);
      expect(calls[0].name).toBe("write_file");
      expect(calls[0].arguments.path).toBe("test.txt");
      expect(calls[0].arguments.content).toBe("hola mundo");
    });

    it("extrae bloques JSON envueltos en markdown ```json ... ```", () => {
      const text =
        'Ejecutando:\n```json\n{\n  "name": "git_status",\n  "arguments": { "flags": ["--short"] }\n}\n```';
      const calls = ToolCallRepairEngine.extractFromText(text);
      expect(calls.length).toBeGreaterThanOrEqual(1);
      expect(calls[0].name).toBe("git_status");
    });
  });

  describe("Coerción y Normalización de Argumentos", () => {
    it("debe normalizar coerción de tipos (números en strings, booleanos y arrays)", () => {
      const rawArgs = {
        timeout: "5000",
        retries: 3,
        enabled: "true",
        disabled: "false",
        flags: "strict",
        doubleQuoted: '""limpio""',
      };

      const normalized = normalizeToolArguments(rawArgs);
      expect(normalized.timeout).toBe(5000);
      expect(normalized.retries).toBe(3);
      expect(normalized.enabled).toBe(true);
      expect(normalized.disabled).toBe(false);
      expect(normalized.flags).toBe("strict");
      expect(normalized.doubleQuoted).toBe("limpio");
    });

    it("prueba directamente las funciones unitarias de coerción", () => {
      expect(coerceBoolean("true")).toBe(true);
      expect(coerceBoolean("1")).toBe(true);
      expect(coerceBoolean("false")).toBe(false);
      expect(coerceBoolean("0")).toBe(false);
      expect(coerceBoolean("random")).toBeUndefined();

      expect(coerceNumber("42")).toBe(42);
      expect(coerceNumber("3.1416")).toBe(3.1416);
      expect(coerceNumber("not_a_number")).toBeUndefined();

      expect(coerceArray("[1, 2, 3]")).toEqual([1, 2, 3]);
      expect(coerceArray("item1, item2, item3")).toEqual(["item1", "item2", "item3"]);
      expect(coerceArray([10, 20])).toEqual([10, 20]);
    });

    it("preserva verbatim las claves de payload (content/text/body/code/script/query/message/prompt): sin trim ni coerción", () => {
      // BUG (coercion.ts:76): el trim incondicional mutaba `content`
      // (ej. trailing newline de fs_write_file) y "true"/"123" se
      // coaccionaban a boolean/number. El payload debe llegar intacto.
      const rawArgs = {
        path: "  src/service.ts  ",
        content: "// Generated by Ego Code Reviewer\nexport function healthCheck(): string {\n  return \"ok\";\n}\n",
        code: "  indented();  ",
        truthy: "true",
        numeric: "123",
      };

      const normalized = normalizeToolArguments({
        content: rawArgs.content,
        code: rawArgs.code,
        // Las claves de payload con valores "true"/"123" tampoco se coaccionan:
        // se prueban vía prefijo preservado usando `content` anidado.
        nested: { content: rawArgs.truthy },
        countAsContent: rawArgs.numeric,
        path: rawArgs.path,
      });

      expect(normalized.content).toBe(rawArgs.content);
      expect(normalized.code).toBe(rawArgs.code);
      expect((normalized.nested as Record<string, unknown>).content).toBe("true");
      // Clave no preservada: el trim/coerción heurística sigue aplicando.
      expect(normalized.path).toBe("src/service.ts");
      expect(normalized.countAsContent).toBe(123);
    });
  });

  describe("ToolCallRepairEngine.repair", () => {
    it("debe reparar una llamada con JSON truncado mediante ToolCallRepairEngine.repair", () => {
      const repaired = ToolCallRepairEngine.repair({
        name: "run_query",
        arguments: '{"query": "SELECT * FROM users", "limit": "50"',
      });

      expect(repaired).not.toBeNull();
      expect(repaired!.name).toBe("run_query");
      expect(repaired!.arguments.query).toBe("SELECT * FROM users");
      expect(repaired!.arguments.limit).toBe(50);
      expect(repaired!.repaired).toBe(true);
    });

    it("retorna intacta una llamada que ya tiene argumentos válidos como objeto", () => {
      const call = {
        name: "fs_read_file",
        arguments: { path: "package.json" },
      };
      const repaired = ToolCallRepairEngine.repair(call);
      expect(repaired).not.toBeNull();
      expect(repaired!.name).toBe("fs_read_file");
      expect(repaired!.arguments.path).toBe("package.json");
    });
  });
});
